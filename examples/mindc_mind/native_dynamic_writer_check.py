#!/usr/bin/env python3
"""Native MIND dynamic ELF writer diagnostics; not compiler qualification.

Explicit scratch composition reuses byte encoders verbatim from main.mind.
The MIND library generates ELF. Python inspects/runs the generated bytes and
independently checks known outputs. No C compiler or assembler is invoked.
MIND_DYNAMIC_SEED and its SHA256 are required; missing tools are a failure.
"""
import hashlib
import os
from pathlib import Path
import re
import resource
import signal
import shutil
import struct
import subprocess

from _stdlib_manifest import seed_blob

HERE = Path(__file__).resolve().parent
LIMIT = 2 * 1024 ** 3


def digest(data):
    return hashlib.sha256(data).hexdigest()


def limited():
    resource.setrlimit(resource.RLIMIT_AS, (LIMIT, LIMIT))
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))


def run(argv, *, data=None, timeout=120):
    env = os.environ.copy()
    for key in list(env):
        if key.startswith("LD_") or key == "GLIBC_TUNABLES":
            env.pop(key)
    env["LC_ALL"] = "C"
    return subprocess.run(argv, input=data, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, timeout=timeout,
                          preexec_fn=limited, env=env)


def encoder(source, name):
    # Named small nb_* encoders have no brace characters in strings/comments.
    match = re.search(r"(?m)^pub fn " + re.escape(name) + r"\(", source)
    assert match, name
    begin = source.index("{", match.start())
    depth = 1
    end = begin + 1
    while depth:
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[match.start():end] + "\n"


def inspect_elf(blob):
    assert blob[:7] == b"\x7fELF\x02\x01\x01"
    typ, machine, version = struct.unpack_from("<HHI", blob, 16)
    assert (typ, machine, version) == (2, 62, 1)
    entry, phoff = struct.unpack_from("<QQ", blob, 24)
    assert entry == 0x401000 and phoff == 64
    phsize, phnum = struct.unpack_from("<HH", blob, 54)
    assert (phsize, phnum) == (56, 9)
    headers = [struct.unpack_from("<IIQQQQQQ", blob, phoff + i * 56)
               for i in range(phnum)]
    loads = [h for h in headers if h[0] == 1]
    assert [h[1] for h in loads] == [4, 5, 4, 6]
    for _, flags, off, va, _, filesz, memsz, align in loads:
        assert filesz <= memsz and off + filesz <= len(blob)
        assert align == 4096 and off % align == va % align
        assert flags & 3 != 3, "writable/executable load"
    for a, b in zip(loads, loads[1:]):
        assert a[3] + a[6] <= b[3], "overlapping virtual loads"
        assert a[2] + a[5] <= b[2], "overlapping file loads"
    assert len(blob) % 4096 == 0
    interp = next(h for h in headers if h[0] == 3)
    assert blob[interp[2]:interp[2] + interp[5]] == b"/lib64/ld-linux-x86-64.so.2\0"
    stack = next(h for h in headers if h[0] == 0x6474e551)
    relro = next(h for h in headers if h[0] == 0x6474e552)
    rw = loads[-1]
    assert stack[1] == 6 and stack[5] == stack[6] == 0
    assert relro[2:4] == rw[2:4] and relro[5:7] == rw[5:7]
    dynamic = next(h for h in headers if h[0] == 2)
    pairs = [struct.unpack_from("<QQ", blob, dynamic[2] + i * 16)
             for i in range(dynamic[5] // 16)]
    assert len(pairs) == 16 and pairs[-1] == (0, 0)
    tags = dict(pairs)
    assert len(tags) == len(pairs)
    assert tags[30] & 8 and tags[0x6ffffffb] & 1, "not eager binding"

    def offset(va, length=1):
        for h in loads:
            if h[3] <= va and va + length <= h[3] + h[5]:
                return h[2] + va - h[3]
        raise AssertionError(f"unmapped address {va:x}")

    strings = offset(tags[5], tags[10])

    def name(index):
        assert 0 <= index < tags[10]
        end = blob.index(b"\0", strings + index, strings + tags[10])
        return blob[strings + index:end].decode("ascii")

    assert name(tags[1]) == "libc.so.6"
    assert tags[11] == 24 and tags[9] == 24 and tags[8] == 48
    symoff = offset(tags[6], 72)
    assert blob[symoff:symoff + 24] == bytes(24)
    symbols = []
    for i in range(1, 3):
        idx, info, other, section, value, size = struct.unpack_from("<IBBHQQ", blob, symoff + i * 24)
        assert (info, other, section, value, size) == (18, 0, 0, 0, 0)
        symbols.append(name(idx))
    assert symbols == sorted(symbols) and symbols[0] == "__libc_start_main"
    hashoff = offset(tags[4], 24)
    assert struct.unpack_from("<6I", blob, hashoff) == (1, 3, 1, 0, 2, 0)
    relas = []
    for i in range(2):
        target, info, addend = struct.unpack_from("<QQq", blob, offset(tags[7]) + i * 24)
        assert info == ((i + 1) << 32) | 6 and addend == 0
        assert rw[3] <= target <= rw[3] + rw[5] - 8
        assert blob[offset(target):offset(target) + 8] == bytes(8)
        relas.append(target)
    for disp, target in zip((32, 50), relas):
        assert blob[4096 + disp - 2:4096 + disp] == b"\xff\x15"
        actual = struct.unpack_from("<i", blob, 4096 + disp)[0]
        assert 0x401000 + disp + 4 + actual == target
    vs = offset(tags[0x6ffffff0], 6)
    versions = struct.unpack_from("<3H", blob, vs)
    assert versions[0] == 0 and set(versions[1:]) == {2, 3}
    assert tags[0x6fffffff] == 1
    need = offset(tags[0x6ffffffe], 48)
    assert struct.unpack_from("<HHIII", blob, need) == (1, 2, 1, 16, 0)
    version_names = []
    for i in range(2):
        _, flags, ident, text, nxt = struct.unpack_from("<IHHII", blob, need + 16 + i * 16)
        assert flags == 0 and ident == i + 2 and nxt == (16 if i == 0 else 0)
        version_names.append(name(text))
    assert version_names == sorted(version_names)
    return symbols, version_names


def main():
    seed = Path(os.environ["MIND_DYNAMIC_SEED"]).resolve()
    expected = os.environ["MIND_DYNAMIC_SEED_SHA256"]
    assert re.fullmatch(r"[0-9a-f]{64}", expected)
    assert digest(seed.read_bytes()) == expected, "seed hash mismatch"
    evidence = Path(os.environ["MIND_DYNAMIC_EVIDENCE"]).resolve()
    evidence.mkdir(parents=True, exist_ok=True)
    preload = Path("/etc/ld.so.preload")
    if preload.exists():
        assert not any(line.partition("#")[0].strip() for line in preload.read_text().splitlines()), "system loader preloads configured"
    observations = []

    def observe(label, result):
        stem = f"{len(observations):03d}-{label}"
        (evidence / f"{stem}.stdout").write_bytes(result.stdout)
        (evidence / f"{stem}.stderr").write_bytes(result.stderr)
        row = f"{stem}\t{result.returncode}\t{digest(result.stdout)}\t{digest(result.stderr)}\n"
        observations.append(row)
        (evidence / "executions.tsv").write_text("id\texit\tstdout_sha256\tstderr_sha256\n" + "".join(observations))
        return result
    source = (HERE / "main.mind").read_text()
    parts = [encoder(source, n) for n in ("nb_push", "nb_le", "nb_u16", "nb_u32", "nb_i64le")]
    library = (HERE / "native_dynamic.mind").read_bytes()
    fixture = (HERE / "native_dynamic_fixture.mind").read_bytes()
    user = "\n".join(parts).encode() + library + b"\n" + fixture
    prefix = seed_blob()
    combined = prefix + user
    # Existing v2 input protocol; 256MiB arena +128MiB stack, under 2GiB RLIMIT_AS.
    packet = struct.pack("<6q", int.from_bytes(b"MINDLAY\x01", "little"),
                         268435456, 134217728, 4096, len(prefix), len(combined)) + combined
    (evidence / "assembled.mind").write_bytes(combined)
    (evidence / "input.packet").write_bytes(packet)
    hashes = {"seed": expected, "library": digest(library), "fixture": digest(fixture),
              "main_source": digest(source.encode()), "stdlib_prefix": digest(prefix),
              "harness": digest(Path(__file__).read_bytes()),
              "assembled": digest(combined), "packet": digest(packet)}
    (evidence / "INPUT_HASHES.txt").write_text("".join(f"{value}  {key}\n" for key, value in hashes.items()))
    build = observe("build", run([str(seed)], data=packet, timeout=180))
    (evidence / "build.stderr").write_bytes(build.stderr)
    (evidence / "build.exit").write_text(str(build.returncode) + "\n")
    assert build.returncode == 0 and build.stderr == b"", (build.returncode, build.stderr)
    assert build.stdout[:4] == b"\x7fELF", f"native build refused: {len(build.stdout)} bytes"
    writer = evidence / "writer.elf"
    writer.write_bytes(build.stdout)
    writer.chmod(0o700)
    hashes["writer"] = digest(build.stdout)
    print(f"BUILD native writer PASS {len(build.stdout)} bytes {hashes['writer']}", flush=True)

    def emit(mode):
        result = observe(f"emit-{mode}", run([str(writer), str(mode)]))
        (evidence / f"case-{mode}.stderr").write_bytes(result.stderr)
        (evidence / f"case-{mode}.exit").write_text(str(result.returncode) + "\n")
        assert result.returncode == 0 and result.stderr == b"", (mode, result.returncode, result.stderr)
        return result.stdout

    startup = bytes.fromhex("31ed4989d15e4889e24883e4f050544531c031c948bf2510400000000000ff1500000000f4")
    nx_body = bytes.fromhex("554889e548b8b84d000000c30000504889e6ba08000000bf01000000b8010000000f054889e0ffd04883c4085dc3")
    assert emit(248) == startup + nx_body, "native fixture source bytes changed before ELF writer"
    baseline = emit(0)
    assert baseline and emit(0) == baseline and emit(1) == baseline, "deterministic/permutation failure"
    symbols, versions = inspect_elf(baseline)
    assert symbols == ["__libc_start_main", "getpid"]
    assert versions == ["GLIBC_2.2.5", "GLIBC_2.34"]
    elf = evidence / "getpid.elf"
    elf.write_bytes(baseline)
    elf.chmod(0o700)
    loader = Path("/lib64/ld-linux-x86-64.so.2").resolve()
    listing = observe("loader-list", run([str(loader), "--list", str(elf)]))
    assert listing.returncode == 0 and listing.stderr == b""
    match = re.search(rb"libc\.so\.6 => (/[^\s]+)", listing.stdout)
    assert match, "libc dependency not resolved by interpreter"
    libc = Path(os.fsdecode(match[1])).resolve()
    version = observe("libc-version", run([str(libc)]))
    assert version.returncode == 0 and version.stderr == b""
    dependencies = [f"{digest(loader.read_bytes())}  {loader}", f"{digest(libc.read_bytes())}  {libc}"]
    cache = Path("/etc/ld.so.cache")
    if cache.exists():
        dependencies.append(f"{digest(cache.read_bytes())}  {cache}")
    (evidence / "DEPENDENCIES.txt").write_text("\n".join(dependencies) + "\nEnvironment: all LD_* and GLIBC_TUNABLES removed; LC_ALL=C; no system preloads.\n")
    for args in ([], ["one", "two"]):
        result = observe(f"getpid-argc-{len(args) + 1}", run([str(elf), *args]))
        assert (result.returncode, result.stdout, result.stderr) == (len(args) + 1, b"", b""), result
    readelf_path = Path(shutil.which("readelf") or "/missing/readelf").resolve()
    hashes["readelf_instrument"] = digest(readelf_path.read_bytes())
    readelf = observe("readelf", run([str(readelf_path), "-W", "-h", "-l", "-d", "-r", "-V", str(elf)]))
    assert readelf.returncode == 0 and not readelf.stderr
    (evidence / "readelf.txt").write_bytes(readelf.stdout)
    hashes["getpid"] = digest(baseline)
    print(f"EXEC real libc getpid + startup argc PASS {hashes['getpid']}", flush=True)

    reasons = {10:1, 11:1, 12:2, 13:5, 14:4, 15:4, 16:3, 17:3, 18:6,
               19:6, 20:7, 21:7, 22:8, 23:9, 24:1, 25:2, 26:2, 27:6,
               28:6, 29:4, 30:4, 31:4, 32:1, 33:2, 34:2}
    for mode, reason in reasons.items():
        assert emit(mode) == b"", f"malformed input {mode} emitted an artifact"
        assert emit(mode + 100) == bytes([reason]), f"wrong rejection reason {mode}"
    print(f"REFUSALS {len(reasons)} malformed input cases PASS, normal exits and exact reasons", flush=True)
    # Observed glibc contract: unresolved symbol=127, missing version=1.
    # Initial diagnostic incorrectly expected127 for both; retain its FAIL receipt.
    for mode, expected_rc, expected_error in ((2, 127, b"undefined symbol"), (3, 1, b"not found"),
                                             (40, 127, b"nd_unreachable_"),
                                             (46, 127, b"nd_missing_unreachable")):
        broken = emit(mode)
        assert broken, "valid unresolved import must reach loader test"
        path = evidence / f"loader-negative-{mode}.elf"
        path.write_bytes(broken)
        path.chmod(0o700)
        result = observe(f"loader-negative-{mode}", run([str(path)]))
        assert result.returncode == expected_rc and result.stdout == b"" and expected_error in result.stderr, result
        (evidence / f"loader-negative-{mode}.stderr").write_bytes(result.stderr)
        print(f"LOADER negative {mode} normal refusal PASS", flush=True)
    for mode in (42, 43):
        boundary = emit(mode)
        inspect_elf(boundary)
        path = evidence / f"boundary-{mode}.elf"
        path.write_bytes(boundary)
        path.chmod(0o700)
        result = observe(f"boundary-{mode}", run([str(path)]))
        assert (result.returncode, result.stdout, result.stderr) == (1, b"", b""), result
        print(f"BOUNDARY {mode} emitted and executed PASS ({len(boundary)} bytes)", flush=True)
    for mode in (47, 48):
        path = evidence / f"protection-{mode}.elf"
        path.write_bytes(emit(mode))
        path.chmod(0o700)
        result = observe(f"protection-{mode}", run([str(path)]))
        assert result.returncode == -signal.SIGSEGV and result.stderr == b"", result
        assert len(result.stdout) == 8, "protection probe failed before checked memory operation"
        if mode == 47:
            assert struct.unpack("<Q", result.stdout)[0] > 0x1000000, "GOT did not hold resolved libc address"
        else:
            assert result.stdout == bytes.fromhex("b84d000000c30000")
        (evidence / f"protection-{mode}.stdout").write_bytes(result.stdout)
        (evidence / f"protection-{mode}.exit").write_text(str(result.returncode) + "\n")
        print(f"PROTECTION {mode} expected fault AFTER valid memory probe PASS (not checker refusal)", flush=True)
    corrupted = bytearray(baseline)
    struct.pack_into("<Q", corrupted, 64 + 3 * 56 + 16, 0x400000)
    try:
        inspect_elf(bytes(corrupted))
    except AssertionError:
        pass
    else:
        raise AssertionError("independent ELF validator missed overlapping segment")
    (evidence / "HASHES.txt").write_text("".join(f"{value}  {key}\n" for key, value in hashes.items()))
    print("PASS native dynamic writer: artifact bytes reproducible; compiler integration remains BLOCKED", flush=True)


if __name__ == "__main__":
    main()
