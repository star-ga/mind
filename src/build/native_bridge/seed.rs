//! The frozen native compiler seed and its std blob, shipped inside `mindc`.
//!
//! `mindc build --backend native` used to read the std seed sources from
//! `./std` and the compiler from a repo-relative `stage1.elf`, so outside a
//! checkout it only worked with `MINDC_STD_DIR` / `MINDC_NATIVE_ELF` set. Both
//! are now embedded at build time. The embedded bytes are not trusted because
//! they were embedded. Each compiler seed is verified against its pin when mindc
//! is built; a mismatch fails the build. `build.rs` hashes `stage1.elf` and
//! compares its size and sha256 with the seed's `MANIFEST.txt` row. The pin and
//! the bytes are compiled into the same binary, so a second hash at run time
//! would stop no one who can change `mindc`. The std blob is hashed for each
//! build and compared with `SEED_BLOB_SHA256` in the std manifest; a mismatch
//! refuses the build. Neither path falls back to a different compiler or blob.
//!
//! The environment overrides keep their meaning exactly: when set, the named
//! file or directory is used as before and the embedded copy is not consulted.

use std::path::{Path, PathBuf};

/// The embedded default-profile compiler seed and its committed manifest.
const DEFAULT_SEED_ELF: &[u8] =
    include_bytes!("../../../examples/mindc_mind/testdata/selfhost_loop/stage1.elf");
/// `build.rs` checks each seed against its manifest; the tests check it again.
#[cfg(test)]
const DEFAULT_SEED_MANIFEST: &str =
    include_str!("../../../examples/mindc_mind/testdata/selfhost_loop/MANIFEST.txt");
/// The embedded bounded-profile compiler seed and its committed manifest.
const BOUNDED_SEED_ELF: &[u8] =
    include_bytes!("../../../examples/mindc_mind/testdata/selfhost_loop_bounded/stage1.elf");
#[cfg(test)]
const BOUNDED_SEED_MANIFEST: &str =
    include_str!("../../../examples/mindc_mind/testdata/selfhost_loop_bounded/MANIFEST.txt");
/// The std manifest that carries the `SEED_BLOB_SHA256` pin.
const STD_MANIFEST: &str =
    include_str!("../../../examples/mindc_mind/testdata/stdlib_manifest.txt");
/// `(module, bytes)` for every `seed` row of the std manifest, in file order,
/// generated by `build.rs` from that manifest.
const EMBEDDED_STD_SEED: &[(&str, &[u8])] =
    include!(concat!(env!("OUT_DIR"), "/native_std_seed.rs"));

/// The std blob pin hash uses the `sha2` crate: it takes the SHA extensions of
/// the host when there are any.
fn sha256_hex(bytes: &[u8]) -> String {
    use sha2::Digest as _;
    sha2::Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// The `stage1.elf<TAB>size<TAB>sha256` row of a seed `MANIFEST.txt`. `build.rs`
/// parses the row with the same rules and refuses to build on a mismatch.
#[cfg(test)]
fn pinned_stage1(manifest: &str) -> Option<(usize, &str)> {
    manifest.lines().find_map(|line| {
        let mut f = line.split('\t');
        if f.next()? != "stage1.elf" {
            return None;
        }
        let size = f.next()?.parse().ok()?;
        let sha = f.next()?.trim();
        (sha.len() == 64).then_some((size, sha))
    })
}

/// The `# SEED_BLOB_SHA256 <hex>` pin of the std manifest.
fn pinned_std_blob_sha(manifest: &str) -> Option<&str> {
    manifest.lines().find_map(|line| {
        let rest = line.strip_prefix('#')?.trim_start();
        let sha = rest.strip_prefix("SEED_BLOB_SHA256")?.trim();
        (sha.len() == 64 && sha.bytes().all(|b| b.is_ascii_hexdigit())).then_some(sha)
    })
}

/// Return `elf` only if its size and sha256 equal the manifest's `stage1.elf` row.
#[cfg(test)]
fn verified_seed<'a>(elf: &'a [u8], manifest: &str, what: &str) -> Result<&'a [u8], String> {
    let (size, sha) = pinned_stage1(manifest).ok_or_else(|| {
        format!("the embedded {what} seed manifest has no `stage1.elf` size/sha256 row")
    })?;
    let actual = sha256_hex(elf);
    if elf.len() != size || actual != sha {
        return Err(format!(
            "the embedded {what} compiler seed does not match its pinned manifest \
             (embedded {} bytes, sha256 {actual}; pinned {size} bytes, sha256 {sha})",
            elf.len()
        ));
    }
    Ok(elf)
}

/// Return the per-module std sources only if their names are the manifest's
/// seed rows in order and their composed blob hashes to `SEED_BLOB_SHA256`.
fn verified_std_seed(
    table: &[(&str, &'static [u8])],
    modules: &[&str],
    manifest: &str,
) -> Result<Vec<Vec<u8>>, String> {
    let names: Vec<&str> = table.iter().map(|(m, _)| *m).collect();
    if names != modules {
        return Err(format!(
            "the embedded std seed modules {names:?} are not the manifest's seed rows {modules:?}"
        ));
    }
    let pinned = pinned_std_blob_sha(manifest)
        .ok_or("the std manifest has no `SEED_BLOB_SHA256` pin".to_string())?;
    let sources: Vec<Vec<u8>> = table.iter().map(|(_, b)| b.to_vec()).collect();
    let blob = crate::build::native_image::compose_std_blob(&sources);
    let actual = sha256_hex(blob.as_bytes());
    if actual != pinned {
        return Err(format!(
            "the embedded std seed blob hashes to {actual}, but the manifest pins \
             SEED_BLOB_SHA256 {pinned}"
        ));
    }
    Ok(sources)
}

/// The std seed sources, in manifest order: from `MINDC_STD_DIR` when it is
/// set, otherwise the verified embedded copy.
pub(super) fn std_seed_sources(modules: &[&str]) -> Result<Vec<Vec<u8>>, String> {
    let Some(dir) = std::env::var_os("MINDC_STD_DIR") else {
        return verified_std_seed(EMBEDDED_STD_SEED, modules, STD_MANIFEST).map_err(|e| {
            format!("{e}. Refusing rather than compiling against an unpinned std blob.")
        });
    };
    let dir = PathBuf::from(dir);
    modules
        .iter()
        .map(|m| {
            let p = dir.join(format!("{m}.mind"));
            std::fs::read(&p).map_err(|e| {
                format!(
                    "cannot read std module '{}': {e} (MINDC_STD_DIR is set to '{}')",
                    p.display(),
                    dir.display()
                )
            })
        })
        .collect()
}

/// The compiler ELF to run. `_unpacked` owns the private directory an embedded
/// seed is written to, which is removed when this value is dropped.
pub(super) struct CompilerElf {
    pub(super) path: PathBuf,
    _unpacked: Option<tempfile::TempDir>,
}

/// The bytes `nb_cap_scoped_nested_bindings` in `examples/mindc_mind/main.mind`
/// compiles to: `movabs rax, imm64` whose little-endian immediate spells
/// `nbscope1`. A compiler built from a `main.mind` that gives every nested `let`
/// its own storage (checked by `self_host_native_shadow_scope_smoke.py`)
/// carries it; no earlier seed does, and those merge nested bindings by name.
pub(super) const SCOPED_BINDINGS_MARK: &[u8] = b"\x48\xb8nbscope1";

/// Versioned compiler compatibility marker for native-lane-v1 admission.
/// Unlike `nbscope1`, it denotes the complete merged lane implementation.
/// It is NOT a signature, a trusted compiler hash, or a qualified release pin.
/// Explicit compiler overrides remain caller-supplied compiler executables;
/// this marker only chooses which source/IR admission contract to apply.
pub(super) const NATIVE_LANE_V1_MARK: &[u8] = b"\x48\xb8nblane01";

/// Compatibility marker for fixed-arity `extern "C"` lowering: `main.mind`'s
/// `nb_cap_extern_fixed_v1` compiles to `movabs rax, imm64` spelling
/// `nbextc01`. A compiler carrying it binds the `nbx_row` libc table through a
/// static-layout dynamic image. Like `nblane01` it selects an admission
/// contract; it is not a signature, a trusted hash, or a release pin.
pub(super) const EXTERN_FIXED_MARK: &[u8] = b"\x48\xb8nbextc01";

/// Compatibility marker for seed-region extern binding: `nbx_bind.mind`'s
/// `nbs_cap_seed_extern_v1` compiles to `movabs rax, imm64` spelling
/// `nbsext01`. A compiler carrying it binds the std seed declarations that
/// kept seed functions call. It selects an admission contract; it is not a
/// signature, a trusted hash, or a release pin.
pub(super) const SEED_EXTERN_MARK: &[u8] = b"\x48\xb8nbsext01";

/// Compatibility marker for the builtin `print` statement: `nb_print.mind`'s
/// `nb_cap_native_print_v1` compiles to `movabs rax, imm64` spelling
/// `nbprint1`. Only a compiler carrying it gets `print` admitted (the lane
/// otherwise refuses it as `lane.source.print`). Like `nblane01` it selects an
/// admission contract; it is not a signature, a trusted hash, or a release pin.
pub(super) const NATIVE_PRINT_MARK: &[u8] = b"\x48\xb8nbprint1";

/// True when the compiler `compiler_elf(bounded)` would run carries
/// [`SCOPED_BINDINGS_MARK`]: the `MINDC_NATIVE_ELF` override when set (an
/// unreadable file reads as unmarked), else the embedded seed of the profile.
pub(super) fn compiler_scopes_nested_bindings(bounded: bool) -> bool {
    compiler_has_mark(bounded, SCOPED_BINDINGS_MARK)
}

pub(super) fn compiler_supports_native_lane_v1(bounded: bool) -> bool {
    compiler_has_mark(bounded, NATIVE_LANE_V1_MARK)
}

pub(super) fn compiler_supports_native_print(bounded: bool) -> bool {
    compiler_has_mark(bounded, NATIVE_PRINT_MARK)
}

pub(super) fn compiler_supports_extern_fixed(bounded: bool) -> bool {
    compiler_has_mark(bounded, EXTERN_FIXED_MARK)
}

/// Both marks: a seed declaration binds through the `nbextc01` table.
pub(super) fn compiler_binds_seed_externs(bounded: bool) -> bool {
    compiler_has_mark(bounded, EXTERN_FIXED_MARK) && compiler_has_mark(bounded, SEED_EXTERN_MARK)
}

#[cfg(test)]
fn has_mark(bytes: &[u8], mark: &[u8]) -> bool {
    bytes.windows(mark.len()).any(|w| w == mark)
}

/// Every compatibility mark, in the bit order of [`marks_in`].
const MARKS: [&[u8]; 5] = [
    SCOPED_BINDINGS_MARK,
    NATIVE_LANE_V1_MARK,
    EXTERN_FIXED_MARK,
    SEED_EXTERN_MARK,
    NATIVE_PRINT_MARK,
];

/// What every mark starts with: `movabs rax, imm64` and the `nb` of its name.
const MARK_PREFIX: &[u8; 4] = b"\x48\xb8nb";

/// Bit `i` is set when `bytes` carries `MARKS[i]`. One pass finds them all: a
/// build asks for five marks, and one scan of the 3.4 MB seed per mark cost
/// 10 ms.
fn marks_in(bytes: &[u8]) -> u8 {
    let mut found = 0;
    for w in bytes.windows(MARKS[0].len()) {
        if w[..4] == *MARK_PREFIX {
            for (bit, mark) in MARKS.iter().enumerate() {
                found |= u8::from(w == *mark) << bit;
            }
        }
    }
    found
}

/// Where the compiler of one build comes from: the file `MINDC_NATIVE_ELF`
/// names, or the embedded seed of the profile, unpacked for this build.
enum Seed {
    Override(PathBuf),
    Embedded(&'static [u8]),
}

/// `(marks, [(size, marks) of the default seed, of the bounded seed])`, as
/// `build.rs` scanned the seeds it verified.
const BUILT_SEED_MARKS: ([&[u8]; 5], [(usize, u8); 2]) =
    include!(concat!(env!("OUT_DIR"), "/native_seed_marks.rs"));

/// The marks of an embedded seed: the ones `build.rs` found, while its mark list
/// and the seed's size equal this build's; otherwise one scan of the bytes.
fn embedded_marks(elf: &[u8], bounded: bool) -> u8 {
    let (list, seeds) = BUILT_SEED_MARKS;
    match seeds[usize::from(bounded)] {
        (size, marks) if size == elf.len() && list == MARKS => marks,
        _ => marks_in(elf),
    }
}

/// Resolve the compiler and its marks once per process. The embedded seed is
/// not hashed or scanned here: `build.rs` verified it and found its marks.
fn resolved(bounded: bool) -> &'static (Seed, u8) {
    static RESOLVED: [std::sync::OnceLock<(Seed, u8)>; 2] =
        [std::sync::OnceLock::new(), std::sync::OnceLock::new()];
    RESOLVED[usize::from(bounded)].get_or_init(|| {
        if let Some(p) = std::env::var_os("MINDC_NATIVE_ELF") {
            // An unreadable override reads as unmarked; `compiler_elf` reports it.
            let marks = std::fs::read(&p).map_or(0, |b| marks_in(&b));
            return (Seed::Override(PathBuf::from(p)), marks);
        }
        let elf = if bounded {
            BOUNDED_SEED_ELF
        } else {
            DEFAULT_SEED_ELF
        };
        (Seed::Embedded(elf), embedded_marks(elf, bounded))
    })
}

fn compiler_has_mark(bounded: bool, mark: &[u8]) -> bool {
    let found = resolved(bounded).1;
    let bit = MARKS.iter().position(|m| *m == mark);
    bit.is_some_and(|bit| (found >> bit) & 1 == 1)
}

/// Resolve the compiler: `MINDC_NATIVE_ELF` when set (it must exist), otherwise
/// the embedded seed for the requested profile (verified against its pin when
/// mindc was built), written to a private temporary directory so it can be
/// executed.
pub(super) fn compiler_elf(bounded: bool) -> Result<CompilerElf, String> {
    match &resolved(bounded).0 {
        Seed::Override(path) if path.exists() => Ok(CompilerElf {
            path: path.clone(),
            _unpacked: None,
        }),
        Seed::Override(path) => Err(format!(
            "pure-MIND compiler ELF not found at '{}' (MINDC_NATIVE_ELF is set)",
            path.display()
        )),
        Seed::Embedded(bytes) => unpacked(bytes),
    }
}

/// Write the embedded seed `bytes` to a new private temporary directory.
fn unpacked(bytes: &[u8]) -> Result<CompilerElf, String> {
    let dir = tempfile::Builder::new()
        .prefix("mindc-native-seed-")
        .tempdir()
        .map_err(|e| format!("cannot create a directory for the embedded compiler seed: {e}"))?;
    let path = dir.path().join("stage1.elf");
    write_executable(&path, bytes).map_err(|e| {
        format!(
            "cannot unpack the embedded compiler seed to '{}': {e}",
            path.display()
        )
    })?;
    Ok(CompilerElf {
        path,
        _unpacked: Some(dir),
    })
}

/// Write `bytes` to a new file and mark it owner-executable. The writer is
/// closed before returning, so no writable descriptor is open at `execve`.
/// Not synced: the file is run once from the page cache and then removed, and
/// the `fsync` of 3.4 MB was 10 ms of every native build.
fn write_executable(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    use std::io::Write as _;
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;
    f.write_all(bytes)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        f.set_permissions(std::fs::Permissions::from_mode(0o700))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lane_marker_is_distinct_complete_and_not_memory_profile_authority() {
        assert!(!has_mark(SCOPED_BINDINGS_MARK, NATIVE_LANE_V1_MARK));
        assert!(!has_mark(b"nblane01", NATIVE_LANE_V1_MARK));
        assert!(!has_mark(b"\x48\xb8nblane02", NATIVE_LANE_V1_MARK));
        assert!(has_mark(
            b"prefix\x48\xb8nblane01suffix",
            NATIVE_LANE_V1_MARK
        ));
        // Neither a bounded-layout label nor the scoped-let marker alone
        // activates new rules. Real pins may be refreshed later, so do not
        // hardcode that every future committed seed must remain unmarked.
        assert!(!has_mark(b"bounded\x48\xb8nbscope1", NATIVE_LANE_V1_MARK));
    }

    #[test]
    fn extern_fixed_marker_is_distinct_from_the_other_marks() {
        assert_eq!(EXTERN_FIXED_MARK.len(), NATIVE_LANE_V1_MARK.len());
        assert!(!has_mark(NATIVE_LANE_V1_MARK, EXTERN_FIXED_MARK));
        assert!(!has_mark(SCOPED_BINDINGS_MARK, EXTERN_FIXED_MARK));
        assert!(!has_mark(b"nbextc01", EXTERN_FIXED_MARK));
        assert!(has_mark(b"x\x48\xb8nbextc01y", EXTERN_FIXED_MARK));
        // main.mind's nb_cap_extern_fixed_v1 immediate spells exactly these bytes.
        let main = std::fs::read_to_string(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/examples/mindc_mind/main.mind"
        ))
        .expect("main.mind is part of the checkout");
        let imm: i64 = 3544442258627846766;
        assert!(main.contains(&format!(
            "pub fn nb_cap_extern_fixed_v1() -> i64 {{\n    {imm}\n}}"
        )));
        assert_eq!(&imm.to_le_bytes(), &EXTERN_FIXED_MARK[2..]);
    }

    #[test]
    fn the_embedded_seeds_carry_the_native_lane_v1_and_scoped_binding_marks() {
        // `compiler_supports_native_lane_v1` reads these bytes when no
        // MINDC_NATIVE_ELF override is set. A seed without the `nblane01` mark
        // sends every native build down the historical admission branch, which
        // has no intrinsic bindings and refuses the downstream consumer programs at the
        // closure fence. The reseed that embeds main.mind's
        // `nb_cap_native_lane_v1` must reach BOTH profiles.
        for (what, elf) in [("default", DEFAULT_SEED_ELF), ("bounded", BOUNDED_SEED_ELF)] {
            assert!(
                has_mark(elf, NATIVE_LANE_V1_MARK),
                "the embedded {what} seed does not carry the native-lane-v1 mark"
            );
            assert!(
                has_mark(elf, SCOPED_BINDINGS_MARK),
                "the embedded {what} seed does not carry the scoped-bindings mark"
            );
        }
    }

    #[test]
    fn one_pass_finds_exactly_the_marks_each_scan_finds() {
        for mark in MARKS {
            assert_eq!((&mark[..4], mark.len()), (&MARK_PREFIX[..], MARKS[0].len()));
        }
        let mut one = b"x\x48\xb8nb\x48\xb8nblane0".to_vec();
        one.extend_from_slice(NATIVE_PRINT_MARK);
        let cut = &one[..one.len() - 1];
        for elf in [DEFAULT_SEED_ELF, BOUNDED_SEED_ELF, &one[..], cut, &b""[..]] {
            for (bit, mark) in MARKS.iter().enumerate() {
                let found = (marks_in(elf) >> bit) & 1 == 1;
                assert_eq!(found, has_mark(elf, mark), "mark {bit}");
            }
        }
        assert_eq!(
            (marks_in(&one), marks_in(cut)),
            (1 << 4, 0),
            "the print mark alone"
        );
    }

    #[test]
    fn the_marks_build_rs_found_are_the_marks_of_the_embedded_seeds() {
        let (list, seeds) = BUILT_SEED_MARKS;
        assert_eq!(list, MARKS, "build.rs scanned for another mark list");
        for (bounded, elf) in [(false, DEFAULT_SEED_ELF), (true, BOUNDED_SEED_ELF)] {
            let built = seeds[usize::from(bounded)];
            assert_eq!(built, (elf.len(), marks_in(elf)), "bounded={bounded}");
            assert_eq!(embedded_marks(elf, bounded), marks_in(elf));
        }
        // A seed of another size (a stale OUT_DIR) is scanned, not trusted.
        let cut = &DEFAULT_SEED_ELF[..DEFAULT_SEED_ELF.len() - 1];
        assert_eq!(embedded_marks(cut, false), marks_in(cut));
        assert_eq!(embedded_marks(b"", true), 0);
    }

    #[test]
    fn the_pin_hash_agrees_with_the_seam_and_the_fips_vectors() {
        let check = |input: &[u8], want: &str| {
            let seam = crate::deps::mini_sha256(input);
            let seam: String = seam.iter().map(|b| format!("{b:02x}")).collect();
            assert_eq!((sha256_hex(input).as_str(), seam.as_str()), (want, want));
        };
        // Empty, one block, a tail that pads into a second block, many blocks.
        check(
            b"",
            "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        );
        check(
            b"abc",
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
        );
        let two = b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
        check(
            two,
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1",
        );
        let million = vec![b'a'; 1_000_000];
        check(
            &million,
            "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0",
        );
    }

    #[test]
    fn the_unpacked_seed_is_the_embedded_seed_and_is_removed_on_drop() {
        let elf = unpacked(BOUNDED_SEED_ELF).expect("unpack");
        let path = elf.path.clone();
        assert_eq!(std::fs::read(&path).expect("unpacked"), BOUNDED_SEED_ELF);
        drop(elf);
        assert!(!path.exists() && !path.parent().unwrap().exists());
    }

    #[test]
    fn the_embedded_default_and_bounded_seeds_match_their_pins() {
        assert!(verified_seed(DEFAULT_SEED_ELF, DEFAULT_SEED_MANIFEST, "default").is_ok());
        assert!(verified_seed(BOUNDED_SEED_ELF, BOUNDED_SEED_MANIFEST, "bounded").is_ok());
    }

    #[test]
    fn a_seed_differing_by_one_bit_is_refused() {
        let mut elf = DEFAULT_SEED_ELF.to_vec();
        elf[1000] ^= 1;
        let err = verified_seed(&elf, DEFAULT_SEED_MANIFEST, "default").unwrap_err();
        assert!(err.contains("does not match its pinned manifest"), "{err}");
    }

    #[test]
    fn a_seed_with_a_different_length_is_refused() {
        let elf = &DEFAULT_SEED_ELF[..DEFAULT_SEED_ELF.len() - 1];
        assert!(verified_seed(elf, DEFAULT_SEED_MANIFEST, "default").is_err());
    }

    #[test]
    fn the_embedded_std_seed_matches_the_manifest_pin() {
        let modules = super::super::frozen_std_seed_modules();
        assert_eq!(EMBEDDED_STD_SEED.len(), 21, "one entry per seed row");
        let sources = verified_std_seed(EMBEDDED_STD_SEED, &modules, STD_MANIFEST)
            .expect("embedded std seed must match SEED_BLOB_SHA256");
        assert_eq!(sources.len(), modules.len());
    }

    #[test]
    fn a_changed_std_module_is_refused() {
        let modules = super::super::frozen_std_seed_modules();
        let mut altered: Vec<(&str, &'static [u8])> = EMBEDDED_STD_SEED.to_vec();
        altered[3].1 = b"fn tampered() -> i64 { return 0; }\n";
        let err = verified_std_seed(&altered, &modules, STD_MANIFEST).unwrap_err();
        assert!(err.contains("SEED_BLOB_SHA256"), "{err}");
    }

    #[test]
    fn a_reordered_std_seed_is_refused() {
        let modules = super::super::frozen_std_seed_modules();
        let mut altered: Vec<(&str, &'static [u8])> = EMBEDDED_STD_SEED.to_vec();
        altered.swap(0, 1);
        assert!(verified_std_seed(&altered, &modules, STD_MANIFEST).is_err());
    }

    #[test]
    fn the_generated_table_bakes_in_no_checkout_path() {
        // OUT_DIR is shared by every checkout that shares a target directory
        // and build.rs only reruns when the manifest changes, so a baked-in
        // absolute path made one checkout embed another checkout's std.
        let generated = include_str!(concat!(env!("OUT_DIR"), "/native_std_seed.rs"));
        assert!(
            !generated.contains(env!("CARGO_MANIFEST_DIR")),
            "{generated}"
        );
        assert_eq!(
            generated.matches("env!(\"CARGO_MANIFEST_DIR\")").count(),
            EMBEDDED_STD_SEED.len(),
            "{generated}"
        );
    }

    #[test]
    fn a_manifest_without_pins_is_refused() {
        assert!(verified_seed(DEFAULT_SEED_ELF, "# nothing\n", "default").is_err());
        let modules = super::super::frozen_std_seed_modules();
        assert!(verified_std_seed(EMBEDDED_STD_SEED, &modules, "# nothing\n").is_err());
    }
}
